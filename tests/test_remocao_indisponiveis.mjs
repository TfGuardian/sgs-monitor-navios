// Executar com node; dependencia de teste instalada em tmp/webhook-validation.
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
const require = createRequire(import.meta.url);
const {PGlite} = require('../tmp/webhook-validation/node_modules/@electric-sql/pglite');
const db = new PGlite();
await db.exec(`
create role anon; create role authenticated; create role service_role;
create table navios_monitorados(id bigint generated by default as identity primary key, situacao text);
create table coletas_monitoramento(id bigint primary key);
`);
for (const arquivo of ['20260914120000_lista_monitoramento_chat.sql','20260921190000_atualizacao_sob_demanda.sql','20260923120000_confirmar_indisponiveis.sql']) {
 await db.exec(readFileSync('supabase/migrations/'+arquivo,'utf8'));
}
const telefone='5513999999999';
await db.query('insert into administradores_chat(telefone) values ($1)',[telefone]);
async function preparar(nomes=['A','B']) {
 await db.exec('truncate atualizacoes_chat cascade; truncate lista_monitoramento cascade; truncate confirmacoes_chat');
 const ids=[];
 for (const nome of nomes) {
  const r=await db.query("insert into lista_monitoramento(nome_solicitado,nome_confirmado,nome_normalizado,adicionado_por) values ($1,$1,$1,$2) returning id",[nome,telefone]);
  ids.push(Number(r.rows[0].id));
 }
 const r=await db.query('select solicitar_atualizacao_chat($1) as id',[telefone]);
 const lote=r.rows[0].id;
 await db.query("update atualizacoes_chat set estado='pronto',resultado='sucesso',indisponiveis=$1 where id=$2",[JSON.stringify(ids.map(id=>({id}))),lote]);
 return {lote,ids};
}
async function oferecer(lote,numero=telefone) {
 return (await db.query('select oferecer_remocao_indisponiveis($1,$2) as proposta',[lote,numero])).rows[0].proposta;
}
async function confirmar() {return (await db.query('select confirmar_remocao_chat($1) as nomes',[telefone])).rows[0].nomes;}
let {lote,ids}=await preparar();
assert.equal((await oferecer(lote)).ids.length,2);
assert.equal((await db.query('select * from lista_monitoramento')).rows.length,2,'nao exclui antes de confirmar');
await db.query("insert into navios_monitorados(lista_monitoramento_id,situacao) values ($1,'atualizado')",[ids[1]]);
assert.deepEqual(await confirmar(),['A'],'preserva navio que voltou');
assert.deepEqual(await confirmar(),[],'confirmacao unica');
assert.equal(await oferecer(lote),null,'nao recria apos confirmar');
({lote}=await preparar());
await oferecer(lote);
await db.query('delete from confirmacoes_chat where telefone=$1',[telefone]);
assert.equal(await oferecer(lote),null,'nao recria apos cancelar');
assert.equal((await db.query('select * from lista_monitoramento')).rows.length,2);
({lote}=await preparar());
await oferecer(lote);
await db.exec("update confirmacoes_chat set expira_em=now()-interval '1 minute'");
assert.deepEqual(await confirmar(),[],'expiracao preserva navios');
assert.equal(await oferecer(lote),null);
({lote}=await preparar());
await db.query("insert into confirmacoes_chat values ($1,'remover_navios','{\"ids\":[],\"nomes\":[]}',now(),now()+interval '10 minutes')",[telefone]);
assert.equal(await oferecer(lote),null,'nao substitui remocao manual');
({lote}=await preparar());
await db.exec("update atualizacoes_chat set resultado='falha'");
assert.equal(await oferecer(lote),null,'nao oferece apos falha');
({lote}=await preparar());
await db.exec('update administradores_chat set ativo=false');
assert.equal(await oferecer(lote),null,'nao oferece a usuario revogado');
await assert.rejects(confirmar(), /Sem permissao/);
await db.close();
console.log('SQL validado: migracoes, confirmacao, revalidacao, cancelamento, expiracao e permissoes.');
